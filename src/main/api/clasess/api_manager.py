# Этот файл представляет собой паттерн "Manager" (Менеджер шагов) в архитектуре автотестов.
# Вместо того чтобы в каждом тесте по отдельности создавать объекты UserSteps, AdminSteps
# и других классов со шагами, создается один единый класс ApiManager.
# Он объединяет все шаги (steps) в одном месте. В тестах будет вызываться только ApiManager,
# что делает код тестов чистым, избавляет от дублирования кода и упрощает поддержку.

# List означает, что мы ждем список, а Any — что внутри списка могут быть элементы любого типа.
from typing import List, Any

# Импортируем класс UserSteps, который содержит логику (шаги) для действий обычного пользователя.
from src.main.api.steps.user_steps import UserSteps

# Импортируем класс AdminSteps, который содержит логику (шаги) для действий администратора.
from src.main.api.steps.admin_steps import AdminSteps


# Объявляем класс ApiManager, который будет главным "пультом управления" всеми шагами в API-тестах.
class ApiManager:

    # __init__ — это конструктор класса. Он автоматически вызывается, когда мы создаем объект ApiManager.
    # Параметр 'created_obj' принимает список объектов, созданных во время тестов (например, для их удаления в конце).
    # Аннотация ': List[Any]' строго указывает, что 'created_obj' должен быть списком.
    def __init__(self, created_obj: List[Any]):
        # Создаем экземпляр класса AdminSteps и сохраняем его в атрибут (переменную) внутри ApiManager.
        # Мы передаем туда 'created_obj', чтобы админские шаги тоже знали об этих объектах и могли ими управлять.
        # В тесте это позволит писать аккуратно: api_manager.admin_steps.создать_пользователя()
        self.admin_steps = AdminSteps(created_obj)

        # Точно так же создаем экземпляр класса UserSteps для обычного пользователя и сохраняем в атрибут.
        # Передаем тот же список 'created_obj', чтобы все менеджеры шагов работали с одной и той же корзиной объектов.
        # В тесте это вызовется как: api_manager.user_steps.сделать_заказ()
        self.user_steps = UserSteps(created_obj)
