# Это базовый класс для всех классов с шагами (Steps). Он служит единой точкой инициализации,
# сохраняя ссылку на общий список созданных объектов `created_obj`. Все дочерние классы
# (например, `AdminSteps` и `UserSteps`) наследуют этот конструктор и автоматически получают
# доступ к общему хранилищу сущностей для последующей очистки.

from typing import List, Any

# Объявляем родительский класс BaseSteps для хранения общего состояния между шагами тестов.
class BaseSteps:
    # Конструктор принимает список созданных в тестах объектов для их отслеживания.
    # ':List[Any]' гарантирует, что на вход придет изменяемый список (коллекция).
    def __init__(self, created_obj: List[Any]):
        self.created_obj = created_obj

